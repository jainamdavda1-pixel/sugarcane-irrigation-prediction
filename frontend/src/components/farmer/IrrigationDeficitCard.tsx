import React, { useState } from 'react';
import {
  Droplets,
  HelpCircle,
  ChevronDown,
  ChevronUp,
  Info,
  Sprout,
  Bot,
  Cpu,
} from 'lucide-react';
import type { ModelPredictions } from '../../types/api';
import { useLanguage } from '../../context/LanguageContext';

interface IrrigationDeficitCardProps {
  predictions: ModelPredictions;
  cropAgeDays?: number;
  plantingDate?: string;
  predictionDate?: string;
}

function getSugarcaneStage(days?: number): { stage: string; desc: string } {
  if (days === undefined) return { stage: 'Contextual', desc: 'Planting date not set' };
  if (days < 0) return { stage: 'Future Sowing', desc: 'Planting date is ahead of selected date' };
  if (days <= 35) return { stage: 'Germination Stage (0-35 d)', desc: 'Sprouting & initial root establishment' };
  if (days <= 100) return { stage: 'Tillering Stage (36-100 d)', desc: 'Shoot formation & vegetative tillering' };
  if (days <= 270) return { stage: 'Grand Growth Stage (101-270 d)', desc: 'Peak water demand & cane elongation' };
  if (days <= 365) return { stage: 'Ripening / Maturity (271-365 d)', desc: 'Sucrose accumulation; lower water need' };
  return { stage: 'Ratoon / Harvest Ready (>365 d)', desc: 'Harvesting or subsequent ratoon cycle' };
}

